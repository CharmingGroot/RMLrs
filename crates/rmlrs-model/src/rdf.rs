//! RDF 1.1 terms and quads.

use std::fmt;

pub const XSD: &str = "http://www.w3.org/2001/XMLSchema#";
pub const XSD_STRING: &str = "http://www.w3.org/2001/XMLSchema#string";
pub const XSD_INTEGER: &str = "http://www.w3.org/2001/XMLSchema#integer";
pub const XSD_DOUBLE: &str = "http://www.w3.org/2001/XMLSchema#double";
pub const XSD_BOOLEAN: &str = "http://www.w3.org/2001/XMLSchema#boolean";
pub const RDF: &str = "http://www.w3.org/1999/02/22-rdf-syntax-ns#";
pub const RDF_TYPE: &str = "http://www.w3.org/1999/02/22-rdf-syntax-ns#type";
pub const RDF_LANG_STRING: &str = "http://www.w3.org/1999/02/22-rdf-syntax-ns#langString";
pub const RDF_FIRST: &str = "http://www.w3.org/1999/02/22-rdf-syntax-ns#first";
pub const RDF_REST: &str = "http://www.w3.org/1999/02/22-rdf-syntax-ns#rest";
pub const RDF_NIL: &str = "http://www.w3.org/1999/02/22-rdf-syntax-ns#nil";

/// A literal. `datatype` is always set: plain literals carry `xsd:string`,
/// language-tagged ones `rdf:langString`, as in RDF 1.1.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Literal {
    pub value: String,
    pub datatype: String,
    pub language: Option<String>,
}

impl Literal {
    pub fn simple(value: impl Into<String>) -> Self {
        Literal {
            value: value.into(),
            datatype: XSD_STRING.to_owned(),
            language: None,
        }
    }

    pub fn typed(value: impl Into<String>, datatype: impl Into<String>) -> Self {
        Literal {
            value: value.into(),
            datatype: datatype.into(),
            language: None,
        }
    }

    /// Language tags are case-insensitive; they are stored lower-cased so that
    /// equal tags compare equal.
    pub fn lang(value: impl Into<String>, language: impl Into<String>) -> Self {
        Literal {
            value: value.into(),
            datatype: RDF_LANG_STRING.to_owned(),
            language: Some(language.into().to_ascii_lowercase()),
        }
    }
}

#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub enum Term {
    Iri(String),
    BlankNode(String),
    Literal(Literal),
    /// A quoted triple (RDF-star), as generated by RML-star.
    Triple(Box<Triple>),
}

impl Term {
    pub fn iri(s: impl Into<String>) -> Self {
        Term::Iri(s.into())
    }

    pub fn as_iri(&self) -> Option<&str> {
        match self {
            Term::Iri(i) => Some(i),
            _ => None,
        }
    }

    pub fn as_literal(&self) -> Option<&Literal> {
        match self {
            Term::Literal(l) => Some(l),
            _ => None,
        }
    }

    pub fn is_blank(&self) -> bool {
        matches!(self, Term::BlankNode(_))
    }
}

/// A quad. `graph` is `None` for the default graph.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Quad {
    pub subject: Term,
    pub predicate: Term,
    pub object: Term,
    pub graph: Option<Term>,
}

/// A triple, as read from a Turtle document, or quoted in a term.
#[derive(Debug, Clone, PartialEq, Eq, Hash, PartialOrd, Ord)]
pub struct Triple {
    pub subject: Term,
    pub predicate: Term,
    pub object: Term,
}

/// N-Triples / N-Quads string escaping.
pub fn escape_literal(s: &str, out: &mut String) {
    // Writing to a String cannot fail.
    let _ = write_literal_escaped(s, out);
}

/// IRIs in N-Quads cannot hold some characters; they are written as `\uXXXX`.
pub fn escape_iri(s: &str, out: &mut String) {
    let _ = write_iri_escaped(s, out);
}

fn literal_needs_escape(b: u8) -> bool {
    b < 0x20 || b == 0x7f || b == b'"' || b == b'\\'
}

fn iri_needs_escape(b: u8) -> bool {
    b <= 0x20
        || matches!(
            b,
            b'<' | b'>' | b'"' | b'{' | b'}' | b'|' | b'^' | b'`' | b'\\'
        )
}

/// Writes the escaped form of a literal value. Runs without escapes are
/// written in one call; most values have none.
fn write_literal_escaped<W: fmt::Write>(s: &str, out: &mut W) -> fmt::Result {
    let bytes = s.as_bytes();
    let mut start = 0;
    for (i, &b) in bytes.iter().enumerate() {
        if !literal_needs_escape(b) {
            continue;
        }
        out.write_str(&s[start..i])?;
        match b {
            b'\\' => out.write_str("\\\\")?,
            b'"' => out.write_str("\\\"")?,
            b'\n' => out.write_str("\\n")?,
            b'\r' => out.write_str("\\r")?,
            b'\t' => out.write_str("\\t")?,
            0x08 => out.write_str("\\b")?,
            0x0c => out.write_str("\\f")?,
            b => write!(out, "\\u{:04X}", b)?,
        }
        start = i + 1;
    }
    out.write_str(&s[start..])
}

fn write_iri_escaped<W: fmt::Write>(s: &str, out: &mut W) -> fmt::Result {
    let bytes = s.as_bytes();
    let mut start = 0;
    for (i, &b) in bytes.iter().enumerate() {
        if iri_needs_escape(b) {
            out.write_str(&s[start..i])?;
            write!(out, "\\u{:04X}", b)?;
            start = i + 1;
        }
    }
    out.write_str(&s[start..])
}

impl fmt::Display for Term {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self {
            Term::Iri(i) => {
                f.write_str("<")?;
                write_iri_escaped(i, f)?;
                f.write_str(">")
            }
            Term::BlankNode(b) => {
                f.write_str("_:")?;
                f.write_str(b)
            }
            Term::Literal(l) => {
                f.write_str("\"")?;
                write_literal_escaped(&l.value, f)?;
                f.write_str("\"")?;
                if let Some(lang) = &l.language {
                    f.write_str("@")?;
                    f.write_str(lang)
                } else if l.datatype != XSD_STRING {
                    f.write_str("^^<")?;
                    write_iri_escaped(&l.datatype, f)?;
                    f.write_str(">")
                } else {
                    Ok(())
                }
            }
            // N-Triples-star / N-Quads-star.
            Term::Triple(t) => write!(f, "<< {} {} {} >>", t.subject, t.predicate, t.object),
        }
    }
}

impl fmt::Display for Quad {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        write!(f, "{} {} {}", self.subject, self.predicate, self.object)?;
        if let Some(g) = &self.graph {
            write!(f, " {g}")?;
        }
        f.write_str(" .")
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn literal_display() {
        assert_eq!(
            Term::Literal(Literal::simple("a\"b")).to_string(),
            r#""a\"b""#
        );
        assert_eq!(
            Term::Literal(Literal::typed("10", XSD_INTEGER)).to_string(),
            r#""10"^^<http://www.w3.org/2001/XMLSchema#integer>"#
        );
        assert_eq!(
            Term::Literal(Literal::lang("x", "EN")).to_string(),
            r#""x"@en"#
        );
    }
}
